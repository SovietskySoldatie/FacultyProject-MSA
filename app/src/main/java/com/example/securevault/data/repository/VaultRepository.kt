package com.example.securevault.data.repository

import com.example.securevault.data.dao.AuthDao
import com.example.securevault.data.dao.NoteDao
import com.example.securevault.data.entity.AuthEntity
import com.example.securevault.data.entity.NoteEntity
import com.example.securevault.model.Note
import com.example.securevault.model.PrivateNote
import com.example.securevault.model.PublicNote
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map

interface VaultRepository {
    fun isPasswordSetFlow(): Flow<Boolean>
    suspend fun isPasswordSet(): Boolean
    suspend fun verifyPassword(password: String): Boolean
    suspend fun setPassword(password: String)

    fun getNotesFlow(): Flow<List<Note>>
    suspend fun getNoteById(id: Long): Note?
    suspend fun insertNote(note: Note): Long
    suspend fun updateNote(note: Note)
    suspend fun deleteNote(note: Note)
    suspend fun deleteNoteById(id: Long)

    /**
     * Changes the privacy of a Note.
     * Per system requirements:
     * "When changing the privacy of a Note, a new Note is created first, and then the old Note is deleted.
     * Let DB IDs be generated by the DB engine."
     */
    suspend fun changeNotePrivacy(oldNote: Note, newPassword: String?): Note
}

class DefaultVaultRepository(
    private val authDao: AuthDao,
    private val noteDao: NoteDao
) : VaultRepository {

    override fun isPasswordSetFlow(): Flow<Boolean> {
        return authDao.getAuthFlow().map { it != null && it.password.isNotEmpty() }
    }

    override suspend fun isPasswordSet(): Boolean {
        val auth = authDao.getAuth()
        return auth != null && auth.password.isNotEmpty()
    }

    override suspend fun verifyPassword(password: String): Boolean {
        val auth = authDao.getAuth() ?: return false
        return auth.password == password
    }

    override suspend fun setPassword(password: String) {
        authDao.setAuth(AuthEntity(id = 1, password = password))
    }

    override fun getNotesFlow(): Flow<List<Note>> {
        return noteDao.getAllNotesFlow().map { entities ->
            entities.map { it.toDomain() }
        }
    }

    override suspend fun getNoteById(id: Long): Note? {
        return noteDao.getNoteById(id)?.toDomain()
    }

    override suspend fun insertNote(note: Note): Long {
        // ID is 0 so DB auto-generates the primary key
        val entity = NoteEntity.fromDomain(note).copy(id = 0)
        val generatedId = noteDao.insertNote(entity)
        note.id = generatedId
        return generatedId
    }

    override suspend fun updateNote(note: Note) {
        val entity = NoteEntity.fromDomain(note)
        noteDao.updateNote(entity)
    }

    override suspend fun deleteNote(note: Note) {
        noteDao.deleteNoteById(note.id)
    }

    override suspend fun deleteNoteById(id: Long) {
        noteDao.deleteNoteById(id)
    }

    override suspend fun changeNotePrivacy(oldNote: Note, newPassword: String?): Note {
        val trimmedPassword = newPassword?.trim() ?: ""
        val willBePrivate = trimmedPassword.isNotEmpty()

        return if (oldNote.isPrivate() == willBePrivate) {
            // Privacy type did not change; if private and password changed, update in-place
            if (oldNote is PrivateNote && oldNote.password != trimmedPassword) {
                oldNote.password = trimmedPassword
                updateNote(oldNote)
            }
            oldNote
        } else {
            // Requirement: "When changing the privacy of a Note, a new Note is created first, and then the old Note is deleted.
            // Let DB IDs be generated by the DB engine."
            val newNote: Note = if (willBePrivate) {
                PrivateNote(
                    id = 0,
                    title = oldNote.title,
                    content = oldNote.content,
                    password = trimmedPassword
                )
            } else {
                PublicNote(
                    id = 0,
                    title = oldNote.title,
                    content = oldNote.content
                )
            }

            // 1. Create new Note in the DB (ID generated by DB engine)
            val newId = insertNote(newNote)
            newNote.id = newId

            // 2. Delete the old Note from the DB
            deleteNoteById(oldNote.id)

            newNote
        }
    }
}
